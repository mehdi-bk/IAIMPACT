import { chromium } from "@playwright/test"
const base = "http://localhost:3000"
const out = process.argv[2]
const browser = await chromium.launch({ executablePath: "/usr/bin/chromium" })
const ctx = await browser.newContext({ viewport: { width: 1600, height: 960 }, locale: "fr-FR" })
const page = await ctx.newPage()
page.on("pageerror", (e) => console.log("[pageerror]", e.message))
page.on("console", (m) => { if (m.type() === "error") console.log("[console]", m.text().slice(0, 200)) })
await page.request.post(base + "/api/demo", { data: { op: "reset_all" } })
await page.request.post(base + "/api/session", { data: { profile: "camille" } })
await page.goto(base + "/")
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/d-home.png` })
await page.getByRole("button", { name: /Ouvrir Compass/ }).click()
await page.waitForTimeout(900)
await page.screenshot({ path: `${out}/d-compass.png` })
await page.goto(base + "/cartes")
await page.getByRole("button", { name: /Verrouiller temporairement/ }).click()
await page.waitForTimeout(700)
await page.screenshot({ path: `${out}/d-confirm.png` })
await page.getByRole("dialog").getByRole("button", { name: "Confirmer" }).click()
await page.waitForTimeout(1800)
await page.screenshot({ path: `${out}/d-frozen.png` })
await page.request.post(base + "/api/demo", { data: { op: "reset_all" } })
await browser.close()
